"""Challenge issuance router for QuantX REST sidecar.

Layer: sidecar
Depends on: quantx_service.wiring.get_issuer, quantx_service.wiring.get_config, quantx_service.errors.malformed_request_error.MalformedRequestError
Implements: HTTP endpoints POST /v1/challenges and POST /v1/challenge per 08-api-specification.md
Outside: Business logic and challenge lifecycle storage (handled by ChallengeIssuer)
Inside: Request parsing, parameter validation, invoking ChallengeIssuer, and shaping challenge response
Security notes: Nonce is cryptographic random bytes generated by ChallengeIssuer and base64 encoded on the wire.
"""

from __future__ import annotations

import base64
from typing import Any

from fastapi import APIRouter, Depends
from pydantic import BaseModel, Field

from quantx_service.config import ServiceConfig
from quantx_service.errors.malformed_request_error import MalformedRequestError
from quantx_service.wiring import ChallengeIssuer, get_config, get_issuer

router = APIRouter(prefix="/v1", tags=["challenges"])


class ChallengeRequest(BaseModel):
    subject_id: str = Field(..., description="Subject identifier requesting authentication")


class ChallengeResponse(BaseModel):
    challenge_id: str
    nonce: str
    required_mode: str
    expires_at: str


@router.post("/challenges", response_model=ChallengeResponse)
@router.post("/challenge", response_model=ChallengeResponse)
async def create_challenge(
    request: ChallengeRequest,
    issuer: ChallengeIssuer = Depends(get_issuer),
    config: ServiceConfig = Depends(get_config),
) -> dict[str, Any]:
    """Issue a fresh authentication challenge for the requested subject."""
    if not request.subject_id or not request.subject_id.strip():
        raise MalformedRequestError("Field 'subject_id' must be a non-empty string")

    record = issuer.issue(subject_id=request.subject_id.strip())
    nonce_b64 = base64.b64encode(record.nonce).decode("ascii")

    return {
        "challenge_id": record.challenge_id,
        "nonce": nonce_b64,
        "required_mode": config.mode,
        "expires_at": record.expires_at.isoformat(),
    }
